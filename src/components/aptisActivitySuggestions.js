const DEMO_ACTIVITY_SUGGESTIONS = APTIS_ACTIVITY_SUGGESTIONS.filter((suggestion) => suggestion.demoAvailable);

export function getAptisActivitySuggestions(isDemoMode) {
  return isDemoMode ? DEMO_ACTIVITY_SUGGESTIONS : APTIS_ACTIVITY_SUGGESTIONS;
}

export function chooseAptisActivitySuggestion(suggestions, seenIds = [], currentId = "") {
  const previousId = currentId || seenIds[seenIds.length - 1];
  const unseen = suggestions.filter((suggestion) => !seenIds.includes(suggestion.id) && suggestion.id !== previousId);
  const pool = unseen.length ? unseen : suggestions.filter((suggestion) => suggestion.id !== previousId);
  return pool[Math.floor(Math.random() * pool.length)] || suggestions[0];
}
